import { App } from "@octokit/app";
import { Octokit } from "@octokit/rest";
import { env, integrations } from "./env.js";

/**
 * GitHub App: clones private repos (installation token) and opens the integration PR.
 * Without App credentials, public repos are cloned anonymously and PRs are unavailable (zip download instead).
 */
let app: App | undefined;
function ghApp(): App {
  app ??= new App({ appId: env.GITHUB_APP_ID!, privateKey: env.GITHUB_APP_PRIVATE_KEY!.replace(/\\n/g, "\n") });
  return app;
}

export interface RepoRef {
  owner: string;
  repo: string;
  ref?: string;
  subdir?: string;
}

/** Parses https://github.com/o/r, .../tree/<ref>/<subdir>, git@github.com:o/r.git */
export function parseRepoUrl(url: string): RepoRef | null {
  const m = url.match(/github\.com[/:]([^/]+)\/([^/#?]+?)(?:\.git)?(?:\/tree\/([^/]+)(?:\/(.+))?)?\/?$/);
  if (!m) return null;
  return { owner: m[1], repo: m[2], ref: m[3], subdir: m[4] };
}

async function installationIdFor(ref: RepoRef, hint?: number | null): Promise<number | null> {
  if (!integrations.githubApp) return null;
  if (hint) return hint;
  try {
    const { data } = await ghApp().octokit.request("GET /repos/{owner}/{repo}/installation", { owner: ref.owner, repo: ref.repo });
    return data.id;
  } catch {
    return null;
  }
}

export async function installationToken(ref: RepoRef, hint?: number | null): Promise<string | null> {
  const id = await installationIdFor(ref, hint);
  if (!id) return null;
  const { data } = await ghApp().octokit.request("POST /app/installations/{installation_id}/access_tokens", { installation_id: id });
  return data.token;
}

export async function cloneUrl(ref: RepoRef, hint?: number | null): Promise<string> {
  const tok = await installationToken(ref, hint);
  return tok ? `https://x-access-token:${tok}@github.com/${ref.owner}/${ref.repo}.git` : `https://github.com/${ref.owner}/${ref.repo}.git`;
}

export interface PrFile {
  path: string;
  content: string;
}

/** Creates branch kronos/integrate-<version>, commits all files in one tree, opens a PR. */
export async function openIntegrationPr(
  ref: RepoRef,
  installationHint: number | null | undefined,
  version: string,
  files: PrFile[],
  title: string,
  body: string,
): Promise<string> {
  const token = await installationToken(ref, installationHint);
  if (!token) throw new Error("The Kronos GitHub App is not installed on this repository");
  const gh = new Octokit({ auth: token });
  const { data: repo } = await gh.repos.get({ owner: ref.owner, repo: ref.repo });
  const base = ref.ref ?? repo.default_branch;
  const { data: baseRef } = await gh.git.getRef({ owner: ref.owner, repo: ref.repo, ref: `heads/${base}` });
  const baseSha = baseRef.object.sha;
  const { data: baseCommit } = await gh.git.getCommit({ owner: ref.owner, repo: ref.repo, commit_sha: baseSha });
  const prefix = ref.subdir ? `${ref.subdir.replace(/\/$/, "")}/` : "";
  const { data: tree } = await gh.git.createTree({
    owner: ref.owner,
    repo: ref.repo,
    base_tree: baseCommit.tree.sha,
    tree: files.map((f) => ({ path: prefix + f.path, mode: "100644" as const, type: "blob" as const, content: f.content })),
  });
  const { data: commit } = await gh.git.createCommit({
    owner: ref.owner,
    repo: ref.repo,
    message: `${title}\n\nGenerated by Kronos ${version}`,
    tree: tree.sha,
    parents: [baseSha],
  });
  const branch = `kronos/integrate-${version}`;
  try {
    await gh.git.createRef({ owner: ref.owner, repo: ref.repo, ref: `refs/heads/${branch}`, sha: commit.sha });
  } catch {
    await gh.git.updateRef({ owner: ref.owner, repo: ref.repo, ref: `heads/${branch}`, sha: commit.sha, force: true });
  }
  const existing = await gh.pulls.list({ owner: ref.owner, repo: ref.repo, head: `${ref.owner}:${branch}`, state: "open" });
  if (existing.data[0]) return existing.data[0].html_url;
  const { data: pr } = await gh.pulls.create({ owner: ref.owner, repo: ref.repo, head: branch, base, title, body });
  return pr.html_url;
}
