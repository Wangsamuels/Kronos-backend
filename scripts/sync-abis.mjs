// Copies compiled ABIs from contracts/out into lib/abi.generated.ts (run after `forge build`).
import fs from "node:fs";
const names = ["KronosGuard", "GuardedMiniLend", "MiniLend", "GuardTimelock", "AttestationRegistry", "MockERC20", "MockAMMOracle", "MockPriceOracle"];
const files = { GuardedMiniLend: "GuardedMiniLend.sol", MiniLend: "MiniLend.sol", MockERC20: "Mocks.sol", MockAMMOracle: "Mocks.sol", MockPriceOracle: "Mocks.sol" };
let out = "// GENERATED by scripts/sync-abis.mjs from contracts/out — do not edit\n";
for (const n of names) {
  const f = files[n] ?? `${n}.sol`;
  const j = JSON.parse(fs.readFileSync(`contracts/out/${f}/${n}.json`, "utf8"));
  out += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(j.abi)} as const;\n`;
}
fs.writeFileSync("lib/abi.generated.ts", out);
console.log("wrote lib/abi.generated.ts");
